/*=============================================================================
  08_validation.sql
  -----------------------------------------------------------------------------
  Project : Enterprise Supply Chain Control Tower
  Phase   : 3 - SQL Data Platform
  Purpose : Prove the SQL layer is trustworthy before Power BI is pointed at it.

  Every check writes a row into #Results with an expected value, the observed
  value and a verdict. The script ends with a single gate: if any check fails,
  it says so explicitly rather than leaving a reader to scan the detail.

  The expected source counts are the ones produced independently by
  Python/01_data_audit.py reading the CSVs with pandas. Using an independent
  count matters - reconciling the load against itself would prove nothing.

  Read-only. Safe to run at any time.
=============================================================================*/

