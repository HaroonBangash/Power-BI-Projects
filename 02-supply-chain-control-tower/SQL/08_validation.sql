/*=============================================================================
  SECTION 3 - Referential integrity
  ---------------------------------------------------------------------------
  The constraints already enforce this, so the meaningful test is whether the
  engine TRUSTS them. An untrusted constraint was created WITH NOCHECK and
  guarantees nothing about existing rows.
=============================================================================*/
INSERT INTO #Results (Section, CheckName, Expected, Actual, [Status], Note)
SELECT 'Referential integrity', 'Foreign keys declared and trusted', '25 trusted',
       CONCAT(COUNT(*), ' declared, ',
              SUM(CASE WHEN is_not_trusted = 0 THEN 1 ELSE 0 END), ' trusted'),
       CASE WHEN COUNT(*) = SUM(CASE WHEN is_not_trusted = 0 THEN 1 ELSE 0 END)
                 AND COUNT(*) >= 25 THEN 'PASS' ELSE 'FAIL' END,
       N'Trusted means SQL Server validated every existing row when the constraint was created.'
FROM sys.foreign_keys WHERE SCHEMA_NAME(schema_id) = 'dbo';

INSERT INTO #Results (Section, CheckName, Expected, Actual, [Status])
SELECT 'Referential integrity', 'Check constraints trusted', 'all trusted',
       CONCAT(COUNT(*), ' declared, ',
              SUM(CASE WHEN is_not_trusted = 0 THEN 1 ELSE 0 END), ' trusted'),
       CASE WHEN COUNT(*) = SUM(CASE WHEN is_not_trusted = 0 THEN 1 ELSE 0 END)
            THEN 'PASS' ELSE 'FAIL' END
FROM sys.check_constraints WHERE SCHEMA_NAME(schema_id) = 'dbo';

