DROP TABLE IF EXISTS #Counts;
CREATE TABLE #Counts (Entity varchar(40), StgRows int, DboRows int, ViewRows int);

DECLARE @Entity varchar(40), @Stg sysname, @Dbo sysname, @Vw sysname, @Sql nvarchar(max);
DECLARE cur CURSOR LOCAL FAST_FORWARD FOR SELECT Entity, StgTable, DboTable, ViewName FROM @Expected;
OPEN cur;
FETCH NEXT FROM cur INTO @Entity, @Stg, @Dbo, @Vw;
WHILE @@FETCH_STATUS = 0
BEGIN
    SET @Sql = N'INSERT INTO #Counts (Entity, StgRows, DboRows, ViewRows)
                 SELECT @e,
                        (SELECT COUNT(*) FROM ' + @Stg + N'),
                        (SELECT COUNT(*) FROM ' + @Dbo + N'),
                        (SELECT COUNT(*) FROM ' + @Vw  + N');';
    EXEC sys.sp_executesql @Sql, N'@e varchar(40)', @e = @Entity;
    FETCH NEXT FROM cur INTO @Entity, @Stg, @Dbo, @Vw;
END
CLOSE cur; DEALLOCATE cur;

-- Source -> staging must always match exactly.
INSERT INTO #Results (Section, CheckName, Expected, Actual, [Status], Note)
SELECT 'Reconciliation',
       CONCAT('Source -> stg : ', e.Entity),
       CAST(e.SourceRows AS varchar(20)),
       CAST(c.StgRows AS varchar(20)),
       CASE WHEN e.SourceRows = c.StgRows THEN 'PASS' ELSE 'FAIL' END,
       NULL
FROM @Expected AS e JOIN #Counts AS c ON c.Entity = e.Entity;

-- staging -> dbo must match, except DimDate which is regenerated by design.
INSERT INTO #Results (Section, CheckName, Expected, Actual, [Status], Note)
SELECT 'Reconciliation',
       CONCAT('stg -> dbo : ', e.Entity),
       CASE WHEN e.Entity = 'DimDate' THEN '2007 (regenerated)' ELSE CAST(c.StgRows AS varchar(20)) END,
       CAST(c.DboRows AS varchar(20)),
       CASE WHEN e.Entity = 'DimDate'
            THEN CASE WHEN c.DboRows = 2007 THEN 'PASS' ELSE 'FAIL' END
            ELSE CASE WHEN c.StgRows = c.DboRows THEN 'PASS' ELSE 'FAIL' END
       END,
       e.Note
FROM @Expected AS e JOIN #Counts AS c ON c.Entity = e.Entity;

-- dbo -> analytics view must match: a view must never lose or multiply facts.
INSERT INTO #Results (Section, CheckName, Expected, Actual, [Status], Note)
SELECT 'Reconciliation',
       CONCAT('dbo -> view : ', e.Entity),
       CAST(c.DboRows AS varchar(20)),
       CAST(c.ViewRows AS varchar(20)),
       CASE WHEN c.DboRows = c.ViewRows THEN 'PASS' ELSE 'FAIL' END,
       CASE WHEN e.Entity = 'FactShipments'
            THEN N'Critical: ProductID is resolved by joining FactSalesOrders. Any drift means the join multiplied or dropped rows.'
            WHEN e.Entity = 'FactPurchaseOrders'
            THEN N'Joins DimProduct to derive purchase price variance.'
       END
FROM @Expected AS e JOIN #Counts AS c ON c.Entity = e.Entity;

