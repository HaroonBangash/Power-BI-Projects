/*=============================================================================
  OUTPUT
=============================================================================*/
SELECT Section, CheckName, Expected, Actual, [Status], Note
FROM   #Results
ORDER BY Seq;

SELECT
    Section,
    Checks = COUNT(*),
    Passed = SUM(CASE WHEN [Status] = 'PASS' THEN 1 ELSE 0 END),
    Failed = SUM(CASE WHEN [Status] = 'FAIL' THEN 1 ELSE 0 END)
FROM   #Results
GROUP BY Section
ORDER BY Section;

SELECT
    TotalChecks = COUNT(*),
    Passed      = SUM(CASE WHEN [Status] = 'PASS' THEN 1 ELSE 0 END),
    Failed      = SUM(CASE WHEN [Status] = 'FAIL' THEN 1 ELSE 0 END),
    Verdict     = CASE WHEN SUM(CASE WHEN [Status] = 'FAIL' THEN 1 ELSE 0 END) = 0
                       THEN 'PHASE 3 QUALITY GATE: PASS'
                       ELSE 'PHASE 3 QUALITY GATE: FAIL - see failed checks above'
                  END
FROM #Results;

